func TestParitySMTPvsDMI(t *testing.T) {
	png := []byte("\x89PNG\r\n\x1a\nparity-image")
	doc := []byte("parity attachment bytes\x00\x01\x02")
	subject := "Rechnung für Ärzte \u2713 Q4"
	raw := buildMIME(t, func(m *gomail.Message) {
		m.SetHeader("Subject", subject)
		m.SetHeader("X-Campaign", "parity")
		m.SetHeader("Reply-To", m.FormatAddress("replies@phish.example.com", "Help Desk"))
		m.SetBody("text/plain", "plain body")
		m.AddAlternative("text/html", `<p>html body</p><img src="cid:logo.png">`)
		m.Embed("logo.png", attachBytes(png))
		m.Attach("report.pdf", attachBytes(doc))
	})

	// Google sends the generated bytes unchanged as the rfc822 part.
	f := newFakeGoogle(t)
	d, err := newGoogleDialer(f.config(t))
	if err != nil {
		t.Fatal(err)
	}
	s, err := d.Dial()
	if err != nil {
		t.Fatal(err)
	}
	if err := s.Send("sender@example.com", []string{"victim@example.com"}, bytesWriterTo(raw)); err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(f.rfc822, raw) {
		t.Fatalf("google rfc822 part differs from generated bytes")
	}

	// Independent reference parse of the same bytes.
	ref, err := email.NewEmailFromReader(bytes.NewReader(raw))
	if err != nil {
		t.Fatal(err)
	}
	msg, large, err := convertToGraph(raw, convNow)
	if err != nil {
		t.Fatal(err)
	}
	if len(large) != 0 {
		t.Fatalf("unexpected large attachments: %d", len(large))
	}

	if msg.Subject != ref.Subject || msg.Subject != subject {
		t.Errorf("subject: graph %q ref %q", msg.Subject, ref.Subject)
	}
	if ref.From == "" || len(ref.To) != 1 {
		t.Fatalf("reference from/to: %q %v", ref.From, ref.To)
	}
	wantFrom := `"Sender Name" <sender@example.com>`
	if ref.From != wantFrom && ref.From != "Sender Name <sender@example.com>" {
		t.Errorf("reference from: %q", ref.From)
	}
	if msg.From.EmailAddress.Address != "sender@example.com" || msg.From.EmailAddress.Name != "Sender Name" {
		t.Errorf("graph from: %+v", msg.From)
	}
	if len(msg.ToRecipients) != 1 || msg.ToRecipients[0].EmailAddress.Address != "victim@example.com" || msg.ToRecipients[0].EmailAddress.Name != "Victim" {
		t.Errorf("graph to: %+v (ref %v)", msg.ToRecipients, ref.To)
	}
	refReply, err := mail.ParseAddress(ref.Headers.Get("Reply-To"))
	if err != nil {
		t.Fatalf("reference reply-to: %q %v", ref.Headers.Get("Reply-To"), err)
	}
	if len(msg.ReplyTo) != 1 || msg.ReplyTo[0].EmailAddress.Address != refReply.Address || msg.ReplyTo[0].EmailAddress.Name != refReply.Name || refReply.Name != "Help Desk" {
		t.Errorf("graph reply-to: %+v (ref %v)", msg.ReplyTo, refReply)
	}
	if got := ref.Headers.Get("Message-Id"); got != "<abc123@example.com>" || extProps(msg)["String 0x1035"] != got {
		t.Errorf("message id: ref %q graph %q", got, extProps(msg)["String 0x1035"])
	}
	// The library skips parts nested in multipart/related, so body and inline parts use a stdlib walk.
	refHTML, refParts := stdlibParts(t, raw)
	if msg.Body.ContentType != "html" || msg.Body.Content != refHTML {
		t.Errorf("html body: graph %q ref %q", msg.Body.Content, refHTML)
	}
	if len(ref.Attachments) != 1 || ref.Attachments[0].Filename != "report.pdf" || !bytes.Equal(ref.Attachments[0].Content, doc) {
		t.Fatalf("reference regular attachment: %+v", ref.Attachments)
	}

	if len(msg.Attachments) != len(refParts) {
		t.Fatalf("attachment count: graph %d ref %d", len(msg.Attachments), len(refParts))
	}
	for _, g := range msg.Attachments {
		r, ok := refParts[g.Name]
		if !ok {
			t.Errorf("attachment %q missing from reference", g.Name)
			continue
		}
		gb, _ := base64.StdEncoding.DecodeString(g.ContentBytes)
		if !bytes.Equal(gb, r.content) {
			t.Errorf("%s: bytes differ", g.Name)
		}
		if g.ContentID != r.cid || g.IsInline != (r.cid != "") {
			t.Errorf("%s: content id graph %q ref %q", g.Name, g.ContentID, r.cid)
		}
	}
	if !bytes.Equal(mustDecode(t, msg.Attachments, "logo.png"), png) || !bytes.Equal(mustDecode(t, msg.Attachments, "report.pdf"), doc) {
		t.Errorf("attachment bytes differ from source")
	}
	if refParts["logo.png"].cid != "logo.png" {
		t.Errorf("reference inline cid: %q", refParts["logo.png"].cid)
	}
}

type refPart struct {
	content []byte
	cid     string
}

func stdlibParts(t *testing.T, raw []byte) (string, map[string]refPart) {
	t.Helper()
	m, err := mail.ReadMessage(bytes.NewReader(raw))
	if err != nil {
		t.Fatal(err)
	}
	var html string
	parts := map[string]refPart{}
	var walk func(h textproto.MIMEHeader, body io.Reader)
	walk = func(h textproto.MIMEHeader, body io.Reader) {
		ct, params, _ := mime.ParseMediaType(h.Get("Content-Type"))
		if strings.HasPrefix(ct, "multipart/") {
			mr := multipart.NewReader(body, params["boundary"])
			for {
				p, err := mr.NextPart()
				if err != nil {
					return
				}
				walk(p.Header, p)
			}
		}
		var r io.Reader = body
		if strings.EqualFold(h.Get("Content-Transfer-Encoding"), "base64") {
			r = base64.NewDecoder(base64.StdEncoding, body)
		}
		data, _ := io.ReadAll(r)
		_, dp, _ := mime.ParseMediaType(h.Get("Content-Disposition"))
		if dp["filename"] == "" {
			if ct == "text/html" {
				html = string(data)
			}
			return
		}
		cid := strings.Trim(h.Get("Content-Id"), "<>")
		if dp["filename"] == "report.pdf" {
			cid = ""
		}
		parts[dp["filename"]] = refPart{data, cid}
	}
	walk(textproto.MIMEHeader(m.Header), m.Body)
	return html, parts
}

func mustDecode(t *testing.T, atts []graphFileAttachment, name string) []byte {
	t.Helper()
	for _, a := range atts {
		if a.Name == name {
			b, err := base64.StdEncoding.DecodeString(a.ContentBytes)
			if err != nil {
				t.Fatal(err)
			}
			return b
		}
	}
	t.Fatalf("no attachment %s", name)
	return nil
}
