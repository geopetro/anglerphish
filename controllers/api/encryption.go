package api

import (
	"encoding/json"
	"errors"
	"net/http"
	"sync"
	"time"

	ctx "github.com/gophish/gophish/context"
	"github.com/gophish/gophish/crypto"
	log "github.com/gophish/gophish/logger"
	"github.com/gophish/gophish/models"
)

const (
	unlockMaxFailures = 5
	unlockWindow      = 15 * time.Minute
)

// failureLimiter counts failed attempts per user id inside a sliding window.
type failureLimiter struct {
	mu       sync.Mutex
	failures map[int64][]time.Time
}

// unlockLimiter throttles failed unlock attempts per admin user.
var unlockLimiter = &failureLimiter{failures: map[int64][]time.Time{}}

// prune drops expired entries for id. The caller must hold l.mu.
func (l *failureLimiter) prune(id int64) []time.Time {
	cutoff := time.Now().Add(-unlockWindow)
	kept := l.failures[id][:0]
	for _, t := range l.failures[id] {
		if t.After(cutoff) {
			kept = append(kept, t)
		}
	}
	if len(kept) == 0 {
		delete(l.failures, id)
	} else {
		l.failures[id] = kept
	}
	return kept
}

func (l *failureLimiter) blocked(id int64) bool {
	l.mu.Lock()
	defer l.mu.Unlock()
	return len(l.prune(id)) >= unlockMaxFailures
}

func (l *failureLimiter) recordFailure(id int64) {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.failures[id] = append(l.prune(id), time.Now())
}

func (l *failureLimiter) clear(id int64) {
	l.mu.Lock()
	defer l.mu.Unlock()
	delete(l.failures, id)
}

func (l *failureLimiter) reset() {
	l.mu.Lock()
	defer l.mu.Unlock()
	l.failures = map[int64][]time.Time{}
}

type encryptionKeyRequest struct {
	Key string `json:"key"`
}

type encryptionMigrateRequest struct {
	Direction string `json:"direction"`
	DryRun    bool   `json:"dry_run"`
}

type encryptionDiscardRequest struct {
	Confirmation string `json:"confirmation"`
}

// encryptionError writes the response for an error from the models layer.
// Only fixed messages are used, never request input.
func encryptionError(w http.ResponseWriter, err error, results []string) {
	var code int
	switch {
	case errors.Is(err, models.ErrWrongKey),
		errors.Is(err, models.ErrBadConfirmation),
		errors.Is(err, crypto.ErrInvalidKeyLength):
		code = http.StatusBadRequest
	case errors.Is(err, models.ErrMigrationRunning),
		errors.Is(err, models.ErrEncryptionAlreadyOn),
		errors.Is(err, models.ErrEncryptedDataExists),
		errors.Is(err, models.ErrNotLocked),
		errors.Is(err, models.ErrNoKeyLoaded),
		errors.Is(err, models.ErrDecryptIncomplete):
		code = http.StatusConflict
	default:
		log.Errorf("encryption: request failed: %v", err)
		JSONResponse(w, models.Response{Success: false, Message: "Encryption request failed"}, http.StatusInternalServerError)
		return
	}
	var data interface{}
	if results != nil {
		data = map[string]interface{}{"results": results}
	}
	JSONResponse(w, models.Response{Success: false, Message: err.Error(), Data: data}, code)
}

func encryptionStatusOrError(w http.ResponseWriter) (models.EncryptionStatus, bool) {
	st, err := models.GetEncryptionStatusInfo()
	if err != nil {
		encryptionError(w, err, nil)
		return st, false
	}
	return st, true
}

func requireMethod(w http.ResponseWriter, r *http.Request, method string) bool {
	if r.Method != method {
		JSONResponse(w, models.Response{Success: false, Message: "Method not allowed"}, http.StatusMethodNotAllowed)
		return false
	}
	return true
}

func decodeBody(w http.ResponseWriter, r *http.Request, v interface{}) bool {
	if err := json.NewDecoder(http.MaxBytesReader(w, r.Body, 1<<16)).Decode(v); err != nil {
		JSONResponse(w, models.Response{Success: false, Message: "Invalid JSON structure"}, http.StatusBadRequest)
		return false
	}
	return true
}

func encryptionUser(r *http.Request) models.User {
	user, _ := ctx.Get(r, "user").(models.User)
	return user
}

// EncryptionStatus returns the current encryption status.
func (as *Server) EncryptionStatus(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodGet) {
		return
	}
	if st, ok := encryptionStatusOrError(w); ok {
		JSONResponse(w, st, http.StatusOK)
	}
}

// EncryptionGenerate returns a fresh key without loading it.
func (as *Server) EncryptionGenerate(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	key, err := crypto.GenerateEncryptionKey()
	if err != nil {
		encryptionError(w, err, nil)
		return
	}
	log.Infof("encryption: key generated by %s", encryptionUser(r).Username)
	w.Header().Set("Cache-Control", "no-store")
	JSONResponse(w, map[string]string{"key": key}, http.StatusOK)
}

// EncryptionEnable turns encryption on with a session key.
func (as *Server) EncryptionEnable(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	req := encryptionKeyRequest{}
	if !decodeBody(w, r, &req) {
		return
	}
	if err := models.EnableEncryptionWithKey(req.Key); err != nil {
		encryptionError(w, err, nil)
		return
	}
	st, ok := encryptionStatusOrError(w)
	if !ok {
		return
	}
	log.Infof("encryption: enable by %s, state=%s", encryptionUser(r).Username, st.State)
	JSONResponse(w, st, http.StatusOK)
}

// EncryptionUnlock leaves the Locked state, rate limited per user.
func (as *Server) EncryptionUnlock(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	user := encryptionUser(r)
	if unlockLimiter.blocked(user.Id) {
		log.Warnf("encryption: unlock rate limit hit by %s", user.Username)
		JSONResponse(w, models.Response{Success: false, Message: "Too many failed attempts; try again later"}, http.StatusTooManyRequests)
		return
	}
	req := encryptionKeyRequest{}
	if !decodeBody(w, r, &req) {
		return
	}
	if err := models.UnlockEncryption(req.Key); err != nil {
		if errors.Is(err, models.ErrWrongKey) || errors.Is(err, crypto.ErrInvalidKeyLength) {
			unlockLimiter.recordFailure(user.Id)
		}
		log.Warnf("encryption: unlock by %s failed", user.Username)
		encryptionError(w, err, nil)
		return
	}
	unlockLimiter.clear(user.Id)
	st, ok := encryptionStatusOrError(w)
	if !ok {
		return
	}
	log.Infof("encryption: unlock by %s, state=%s", user.Username, st.State)
	JSONResponse(w, st, http.StatusOK)
}

// EncryptionMigrate encrypts or decrypts stored values, optionally as a dry run.
func (as *Server) EncryptionMigrate(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	req := encryptionMigrateRequest{}
	if !decodeBody(w, r, &req) {
		return
	}
	if req.Direction != "encrypt" && req.Direction != "decrypt" {
		JSONResponse(w, models.Response{Success: false, Message: "direction must be encrypt or decrypt"}, http.StatusBadRequest)
		return
	}
	encrypt := req.Direction == "encrypt"
	if encrypt {
		// Decrypt-only mode stops encryption; running encrypt there would
		// report misleading counts.
		st, ok := encryptionStatusOrError(w)
		if !ok {
			return
		}
		if st.State == models.EncryptionStateDisabling {
			JSONResponse(w, models.Response{Success: false, Message: "encryption is being disabled; encrypt is not available"}, http.StatusConflict)
			return
		}
	}
	results, err := models.RunEncryptionMigration(encrypt, req.DryRun)
	if err != nil {
		encryptionError(w, err, results)
		return
	}
	st, ok := encryptionStatusOrError(w)
	if !ok {
		return
	}
	log.Infof("encryption: migrate by %s, direction=%s dry_run=%t results=%d plaintext=%d",
		encryptionUser(r).Username, req.Direction, req.DryRun, len(results), st.PlaintextCount)
	JSONResponse(w, map[string]interface{}{"results": results, "status": st}, http.StatusOK)
}

// EncryptionDisable decrypts all values and turns encryption off.
func (as *Server) EncryptionDisable(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	results, err := models.DisableEncryption()
	if err != nil {
		encryptionError(w, err, results)
		return
	}
	st, ok := encryptionStatusOrError(w)
	if !ok {
		return
	}
	log.Infof("encryption: disable by %s, results=%d state=%s", encryptionUser(r).Username, len(results), st.State)
	JSONResponse(w, map[string]interface{}{"results": results, "status": st}, http.StatusOK)
}

// EncryptionDiscard permanently clears encrypted values after confirmation.
func (as *Server) EncryptionDiscard(w http.ResponseWriter, r *http.Request) {
	if !requireMethod(w, r, http.MethodPost) {
		return
	}
	req := encryptionDiscardRequest{}
	if !decodeBody(w, r, &req) {
		return
	}
	report, err := models.DiscardEncryptedData(req.Confirmation)
	if err != nil {
		log.Warnf("encryption: discard by %s refused", encryptionUser(r).Username)
		encryptionError(w, err, nil)
		return
	}
	st, ok := encryptionStatusOrError(w)
	if !ok {
		return
	}
	log.Infof("encryption: discard by %s, state=%s", encryptionUser(r).Username, st.State)
	JSONResponse(w, map[string]interface{}{"discarded": report, "status": st}, http.StatusOK)
}
